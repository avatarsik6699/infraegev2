def _out_of_topic() -> str:
    lines = [
        "| Тип | Задач | Номера |",
        "|---|---:|---|",
    ]
    for key, name in OUT_GROUPS.items():
        ids = [tid for tid, _, group in OUT_OF_TOPIC if group == key]
        links = ", ".join(f"[{tid}]({SOURCE.format(tid)})" for tid in ids)
        lines.append(f"| {name} | {len(ids)} | {links} |")
    dated = [(tid, src) for tid, src, _ in OUT_OF_TOPIC if src]
    lines += [
        "",
        "С пометкой источника: "
        + "; ".join(f"[{tid}]({SOURCE.format(tid)}) — {src}" for tid, src in dated)
        + ".",
    ]
    return "\n".join(lines)


