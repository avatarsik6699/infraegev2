"""Export a topic's code-built figures for the site (pipeline stage 9).

Usage (from the repository root):

    python3 -I scripts/lesson_design/export_media.py content/lesson-design/topic-25
    python3 -I scripts/lesson_design/export_media.py content/lesson-design/topic-25 --check

Every ``%%builder(args)%%`` call in the topic's subtopic and final Markdown is
rebuilt with ``figures.py``:

- a diagram becomes one SVG string;
- a step-through figure (``figures.STEPPERS``) becomes one SVG string per frame;
- an interactive widget (``figures.WIDGETS``) is rendered by its own site
  component; one that draws from generated data (``figures.WIDGET_DATA``,
  topic 23 ``path_builder``) exports that data as its own manifest entry.

The strings go into a typed manifest with sizes, alt text and frame captions,
``apps/web/src/entities/lesson/content/<id>.media.ts``; the site renders them
inline, so their labels use the page font (Onest) — an SVG inside ``<img>``
cannot load webfonts. ``topic.json`` names the site identity:
``"site": {"id": ..., "route": ...}``. ``--check`` rebuilds in memory and fails
when the manifest is stale; a topic without ``site`` is still on the demo stand
(stages 1–8) and has no manifest yet, so ``--check`` skips it.
"""

import argparse
import ast
import hashlib
import html
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
from figures import FIGURES, STEPPERS, WIDGET_DATA, WIDGETS  # noqa: E402

FIGURE_CALL = re.compile(r"%%(\w+)\((.*?)\)%%")
FIGURE_BLOCK = re.compile(r"<figure\b.*?</figure>", re.S)
# builders whose content is in their list arguments: two calls with the same
# scalar arguments still draw different figures (formula_steps of one cell,
# base_blocks of one base)
HASHED = {"formula_steps", "base_blocks"}
TASK_BLOCK = ("**Чтобы проверить понимание", "**Задачи основных подтем")
SVG_NS = 'xmlns="http://www.w3.org/2000/svg"'
STAND_FONT = 'font-family="Onest, system-ui, sans-serif"'
HEADER = (
    "// Generated by scripts/lesson_design/export_media.py from {source}.\n"
    "// Do not edit: change the figure builder or its call and re-export.\n"
)


def topic_sources(topic: Path) -> tuple[dict, list[Path]]:
    meta = json.loads((topic / "topic.json").read_text())
    if "site" not in meta:
        raise SystemExit('topic.json needs "site": {"id": ..., "route": ...}')
    files = [topic / s["source"] for s in meta["subtopics"]] + [topic / meta["final"]["source"]]
    return meta, files


def parse_call(name: str, args_src: str) -> tuple[list, dict]:
    call = ast.parse(f"f({args_src})", mode="eval").body
    assert isinstance(call, ast.Call)
    args = [ast.literal_eval(a) for a in call.args]
    kwargs = {k.arg: ast.literal_eval(k.value) for k in call.keywords}
    return args, kwargs


def prop(indent: int, key: str, value: str) -> str:
    """One object property the way Prettier (width 80) prints it."""
    pad = " " * indent
    line = f"{pad}{key}: {value},"
    return line if len(line) <= 80 else f"{pad}{key}:\n{pad}  {value},"


def media_key(name: str, args: list, kwargs: dict | None = None) -> str:
    """Stable TS identifier: camelCase builder name plus its positional args.
    A call whose arguments are only lists (a graph: its edge list) gets a short
    hash of them and of the keyword arguments instead, so that two pictures of
    one graph (a path, values under the vertices) never share a key; a call with
    keyword arguments gets the hash too, so that two views of one data file
    (points, then their clusters) never share a key either."""
    head, *rest = name.split("_")
    camel = head + "".join(part.title() for part in rest)
    parts = [re.sub(r"[^0-9A-Za-z]", "", str(a)) for a in args if not isinstance(a, list)]
    key = camel + "_".join(p for p in parts if p)
    if (key == camel and args) or kwargs or name in HASHED:
        data = json.dumps([args, kwargs or {}], ensure_ascii=False, sort_keys=True)
        digest = hashlib.sha1(data.encode()).hexdigest()
        key += "_" + digest[:6]
    return key


def ts_string(text: str) -> str:
    """A string literal the way Prettier keeps it: the quote needing fewer escapes."""
    if text.count('"') > text.count("'"):
        return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"
    return json.dumps(text, ensure_ascii=False)


def inline_svg(svg: str) -> tuple[str, int, int, str]:
    """SVG for inline use: text inherits the page font, the wrapper carries
    the accessible name. Returns markup, intrinsic size and alt text."""
    match = re.match(r'<svg viewBox="0 0 (\d+(?:\.\d+)?) (\d+(?:\.\d+)?)"', svg)
    if not match:
        raise SystemExit('figure builder must start with <svg viewBox="0 0 W H"')
    width, height = round(float(match.group(1))), round(float(match.group(2)))
    label = re.search(r'aria-label="([^"]*)"', svg)
    head_match = re.match(r"<svg [^>]*>", svg)
    assert head_match
    head = head_match.group(0)
    clean = re.sub(r' (role|aria-label|aria-hidden)="[^"]*"', "", head)
    clean = clean.replace("<svg ", f'<svg {SVG_NS} aria-hidden="true" focusable="false" ', 1)
    svg = clean + svg[len(head) :]
    svg = svg.replace(STAND_FONT.strip(), 'font-family="inherit"')
    return svg, width, height, label.group(1) if label else ""


def captions(text: str) -> dict[str, str]:
    """Plain figure captions by the builder call they sign: the alt text of a
    diagram whose builder draws no ``aria-label`` (topics 16, 18)."""
    found = {}
    for figure in FIGURE_BLOCK.finditer(text):
        call = FIGURE_CALL.search(figure.group(0))
        caption = re.search(r"<figcaption>(.*?)</figcaption>", figure.group(0), re.S)
        if call and caption:
            plain = re.sub(r"<[^>]+>", "", caption.group(1))
            found[call.group(0)] = html.unescape(" ".join(plain.split()))
    return found


def figure_entries(texts: list[str], seen: set[str] | None = None) -> list[str]:
    """Manifest entries for every ``%%builder(args)%%`` call of the texts."""
    seen = set() if seen is None else seen
    entries: list[str] = []
    for text in texts:
        signed = captions(text)
        for match in FIGURE_CALL.finditer(text):
            name, args_src = match.group(1), match.group(2)
            if name in WIDGETS and name not in WIDGET_DATA:
                continue
            if name not in FIGURES:
                raise SystemExit(f"Unknown figure {name!r}; add it to figures.FIGURES")
            args, kwargs = parse_call(name, args_src)
            key = media_key(name, args, kwargs)
            if key in seen:
                raise SystemExit(f"Two figures share the key {key!r}; vary their arguments")
            seen.add(key)
            if name in WIDGET_DATA:
                # a sandbox drawn by its site component from generated data
                data = WIDGET_DATA[name](*args, **kwargs)
                entries.append(f"  {key}: " + json.dumps(data, ensure_ascii=False) + ",")
                continue
            if name in STEPPERS:
                frames = []
                width = height = 0
                for svg, caption in STEPPERS[name](*args, **kwargs):
                    text_svg, width, height, _ = inline_svg(svg)
                    frames.append(
                        "      {\n"
                        + prop(8, "svg", ts_string(text_svg))
                        + "\n"
                        + prop(8, "caption", ts_string(caption))
                        + "\n      },"
                    )
                entries.append(
                    f'  {key}: {{\n    kind: "stepper",\n    width: {width},\n'
                    f"    height: {height},\n    frames: [\n" + "\n".join(frames) + "\n    ],\n  },"
                )
            else:
                text_svg, width, height, alt = inline_svg(FIGURES[name](*args, **kwargs))
                alt = alt or signed.get(match.group(0), "")
                if not alt:
                    raise SystemExit(
                        f"{key}: a diagram needs aria-label or a figcaption for its alt text"
                    )
                entries.append(
                    f'  {key}: {{\n    kind: "diagram",\n'
                    + prop(4, "svg", ts_string(text_svg))
                    + f"\n    width: {width},\n    height: {height},\n"
                    + prop(4, "alt", ts_string(alt))
                    + "\n  },"
                )
    return entries


def manifest_text(source: Path, entries: list[str]) -> str:
    rel = source.resolve().relative_to(REPO)
    return (
        HEADER.format(source=rel)
        + 'import type { LessonMediaTypes } from "~/shared/components/learning-content";\n\n'
        + "export const lessonMedia = {\n"
        + "\n".join(entries)
        + "\n} as const satisfies Record<string, LessonMediaTypes.Generated>;\n"
    )


def build(topic: Path) -> tuple[str, Path]:
    """Return the manifest text and its target path."""
    meta, sources = topic_sources(topic)
    site = meta["site"]
    manifest_path = REPO / "apps/web/src/entities/lesson/content" / f"{site['id']}.media.ts"
    texts = [lesson_text(source.read_text()) for source in sources]
    return manifest_text(topic, figure_entries(texts) + code_entries(texts)), manifest_path


def lesson_text(text: str) -> str:
    """The steps the site shows: the task block of a page («Чтобы проверить
    понимание…», «Задачи основных подтем…») stays on the stand, and so do the
    book previews (``grid_book``) its tasks open."""
    steps = re.split(r"\n---\n", text)
    return "\n---\n".join(s for s in steps if not s.strip().startswith(TASK_BLOCK))


def code_entries(texts: list[str]) -> list[str]:
    """Runnable code blocks and live sheets of a topic, in the order the lesson
    export meets them, so both name them alike (``runCount``, ``sheet1``)."""
    from export_lesson import Converter  # the lesson export imports this module

    converter = Converter(set(), {}, [])
    for text in texts:
        converter.prepare(text)
    return converter.runs


def prettier(text: str, path: Path) -> str:
    """Format like the repository's format gate, so --check compares equal."""
    return subprocess.run(
        [str(REPO / "node_modules/.bin/prettier"), "--stdin-filepath", str(path)],
        input=text,
        capture_output=True,
        text=True,
        check=True,
        cwd=REPO,
    ).stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    parser.add_argument("topic", type=Path)
    parser.add_argument("--check", action="store_true", help="fail on stale output")
    options = parser.parse_args()
    if options.check and "site" not in json.loads((options.topic / "topic.json").read_text()):
        print(f"{options.topic}: stand only, not exported yet")
        return 0
    manifest, manifest_path = build(options.topic)
    manifest = prettier(manifest, manifest_path)
    rel = manifest_path.relative_to(REPO)
    if options.check:
        stale = not manifest_path.exists() or manifest_path.read_text() != manifest
        print(f"{rel}: {'stale' if stale else 'up to date'}")
        return 1 if stale else 0
    manifest_path.write_text(manifest)
    print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
