"""Export a topic's code-built figures for the site (pipeline stage 9).

Usage (from the repository root):

    python3 -I scripts/lesson_design/export_media.py docs/artifacts/lesson-design/topic-25
    python3 -I scripts/lesson_design/export_media.py docs/artifacts/lesson-design/topic-25 --check

Every ``%%builder(args)%%`` call in the topic's subtopic and final Markdown is
rebuilt with ``figures.py``:

- a diagram becomes one SVG string;
- a step-through figure (``figures.STEPPERS``) becomes one SVG string per frame;
- an interactive widget (``figures.WIDGETS``) is rendered by its own site
  component and exports nothing.

The strings go into a typed manifest with sizes, alt text and frame captions,
``apps/web/src/entities/lesson/content/<id>.media.ts``; the site renders them
inline, so their labels use the page font (Onest) — an SVG inside ``<img>``
cannot load webfonts. ``topic.json`` names the site identity:
``"site": {"id": ..., "route": ...}``. ``--check`` rebuilds in memory and fails
when the manifest is stale.
"""

import argparse
import ast
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
from figures import FIGURES, STEPPERS, WIDGETS  # noqa: E402

FIGURE_CALL = re.compile(r"%%(\w+)\((.*?)\)%%")
SVG_NS = 'xmlns="http://www.w3.org/2000/svg"'
STAND_FONT = 'font-family="Onest, system-ui, sans-serif"' 
HEADER = (
    "// Generated by scripts/lesson_design/export_media.py from {source}.\n"
    "// Do not edit: change the figure builder or its call and re-export.\n"
)


def topic_sources(topic: Path) -> tuple[dict, list[Path]]:
    meta = json.loads((topic / "topic.json").read_text())
    if "site" not in meta:
        raise SystemExit('topic.json needs "site": {"id": ..., "route": ...}')
    files = [topic / s["source"] for s in meta["subtopics"]] + [
        topic / meta["final"]["source"]
    ]
    return meta, files


def parse_call(name: str, args_src: str) -> tuple[list, dict]:
    call = ast.parse(f"f({args_src})", mode="eval").body
    assert isinstance(call, ast.Call)
    args = [ast.literal_eval(a) for a in call.args]
    kwargs = {k.arg: ast.literal_eval(k.value) for k in call.keywords}
    return args, kwargs


def prop(indent: int, key: str, value: str) -> str:
    """One object property the way Prettier (width 80) prints it."""
    pad = " " * indent
    line = f"{pad}{key}: {value},"
    return line if len(line) <= 80 else f"{pad}{key}:\n{pad}  {value},"


def media_key(name: str, args: list) -> str:
    """Stable TS identifier: camelCase builder name plus its positional args."""
    head, *rest = name.split("_")
    camel = head + "".join(part.title() for part in rest)
    parts = [
        re.sub(r"[^0-9A-Za-z]", "", str(a)) for a in args if not isinstance(a, list)
    ]
    return camel + "_".join(p for p in parts if p)


def ts_string(text: str) -> str:
    """A string literal the way Prettier keeps it: the quote needing fewer escapes."""
    if text.count('"') > text.count("'"):
        return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"
    return json.dumps(text, ensure_ascii=False)


def inline_svg(svg: str) -> tuple[str, int, int, str]:
    """SVG for inline use: text inherits the page font, the wrapper carries
    the accessible name. Returns markup, intrinsic size and alt text."""
    match = re.match(r'<svg viewBox="0 0 (\d+(?:\.\d+)?) (\d+(?:\.\d+)?)"', svg)
    if not match:
        raise SystemExit('figure builder must start with <svg viewBox="0 0 W H"')
    width, height = round(float(match.group(1))), round(float(match.group(2)))
    label = re.search(r'aria-label="([^"]*)"', svg)
    head = re.match(r"<svg [^>]*>", svg).group(0)
    clean = re.sub(r' (role|aria-label|aria-hidden)="[^"]*"', "", head)
    clean = clean.replace("<svg ", f'<svg {SVG_NS} aria-hidden="true" focusable="false" ', 1)
    svg = clean + svg[len(head) :]
    svg = svg.replace(STAND_FONT.strip(), 'font-family="inherit"')
    return svg, width, height, label.group(1) if label else ""


def build(topic: Path) -> tuple[str, Path]:
    """Return the manifest text and its target path."""
    meta, sources = topic_sources(topic)
    site = meta["site"]
    manifest_path = (
        REPO / "apps/web/src/entities/lesson/content" / f"{site['id']}.media.ts"
    )
    entries: list[str] = []
    seen: set[str] = set()
    for source in sources:
        for match in FIGURE_CALL.finditer(source.read_text()):
            name, args_src = match.group(1), match.group(2)
            if name in WIDGETS:
                continue
            if name not in FIGURES:
                raise SystemExit(f"Unknown figure {name!r}; add it to figures.FIGURES")
            args, kwargs = parse_call(name, args_src)
            key = media_key(name, args)
            if key in seen:
                raise SystemExit(
                    f"Two figures share the key {key!r}; vary their arguments"
                )
            seen.add(key)
            if name in STEPPERS:
                frames = []
                for svg, caption in STEPPERS[name](*args, **kwargs):
                    text, width, height, _ = inline_svg(svg)
                    frames.append(
                        "      {\n"
                        + prop(8, "svg", ts_string(text))
                        + "\n"
                        + prop(8, "caption", ts_string(caption))
                        + "\n      },"
                    )
                entries.append(
                    f'  {key}: {{\n    kind: "stepper",\n    width: {width},\n'
                    f"    height: {height},\n    frames: [\n"
                    + "\n".join(frames)
                    + "\n    ],\n  },"
                )
            else:
                text, width, height, alt = inline_svg(FIGURES[name](*args, **kwargs))
                if not alt:
                    raise SystemExit(
                        f"{key}: a diagram needs aria-label for its alt text"
                    )
                entries.append(
                    f'  {key}: {{\n    kind: "diagram",\n'
                    + prop(4, "svg", ts_string(text))
                    + f"\n    width: {width},\n    height: {height},\n"
                    + prop(4, "alt", ts_string(alt))
                    + "\n  },"
                )
    rel = topic.resolve().relative_to(REPO)
    manifest = (
        HEADER.format(source=rel)
        + 'import type { LessonMediaTypes } from "~/shared/components/learning-content";\n\n'
        + "export const lessonMedia = {\n"
        + "\n".join(entries)
        + "\n} as const satisfies Record<string, LessonMediaTypes.Generated>;\n"
    )
    return manifest, manifest_path


def prettier(text: str, path: Path) -> str:
    """Format like the repository's format gate, so --check compares equal."""
    return subprocess.run(
        [str(REPO / "node_modules/.bin/prettier"), "--stdin-filepath", str(path)],
        input=text,
        capture_output=True,
        text=True,
        check=True,
        cwd=REPO,
    ).stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("topic", type=Path)
    parser.add_argument("--check", action="store_true", help="fail on stale output")
    options = parser.parse_args()
    manifest, manifest_path = build(options.topic)
    manifest = prettier(manifest, manifest_path)
    rel = manifest_path.relative_to(REPO)
    if options.check:
        stale = not manifest_path.exists() or manifest_path.read_text() != manifest
        print(f"{rel}: {'stale' if stale else 'up to date'}")
        return 1 if stale else 0
    manifest_path.write_text(manifest)
    print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
