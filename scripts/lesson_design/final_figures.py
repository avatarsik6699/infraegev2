"""Figures of «Практика и итог» of the EGE topics (T254, registered in figures.FIGURES).

The final page of a topic reads like the course summary: the topic task as it
grew from subtopic to subtopic, and the order of solving with the subtopics
each step comes from. The data of every topic is ``FINALS[lesson id]``:

- ``task``: the stops of the topic task — ``(subtopic number, title, lines,
  new)``; ``lines`` is the whole draft or program after that subtopic (a line
  not in the previous stop is marked), ``new`` — two short notes beside it;
  ``task_end`` — the tail of the last caption (the answer); ``code_size`` —
  a smaller face for long program lines. A fifth element
  names the side column when several stops share a subtopic.
- ``cycle``: the steps of solving — ``(title, [two lines], subtopics)``;
  ``key`` — the step in accent; ``back`` — ``(from, to, note)``: a failed check
  returns to an earlier step.

- ``frames``: for a visual topic, the topic task as the topic's own figures —
  ``(builder, args, kwargs, caption)``; the caption names the subtopic.

``final_task_stepper(lesson)`` — the topic task subtopic by subtopic.
``final_figure_stepper(lesson)`` — the same with the topic's figures.
``final_cycle(lesson)`` — the order of solving with the subtopic numbers.
"""

