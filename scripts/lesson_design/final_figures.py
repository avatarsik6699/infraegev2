def final_task_frames(lesson: str, tone: str | None = None) -> list[tuple[str, str]]:
    """The topic task across the topic: each frame is the draft after one
    subtopic, its new lines marked with the accent."""
    data = FINALS[lesson]
    stops = data["task"]
    accent = accent_of(tone)
    # ``code_size``: a smaller face for a topic whose program lines are long
    size = data.get("code_size", 12.5)
    line_h, top = round(size * 1.52), 64
    chars = int((452 - 32) / (0.6 * size))
    longest = max(len(stop[2]) for stop in stops)
    # the side column (stop, title, «новое:» and two notes) needs top + 120
    height = max(top + longest * line_h + 16, top + 120)
    # a label like «1 · программа» needs room: wider stops, the first one in
    label = max(len(stop[0]) for stop in stops) * 6.9  # 11.5 px monospace
    x0 = max(24, label / 2 + 4)
    step = min(max(68, label + 16), (W - 2 * x0) / max(len(stops) - 1, 1))
    frames, before = [], set()
    for k, (stop, title, lines, new, *side) in enumerate(stops):
        # the side column names the subtopic; a stop inside one subtopic
        # («1 · программа») passes it as the fifth element
        where = side[0] if side else f"подтема {stop}"
        for line in lines:
            assert len(line) <= chars, f"{lesson}: line too long: {line}"
        out = [f'<svg viewBox="0 0 {W} {height}" role="img" aria-hidden="true">']
        # the subtopics as a strip of stops; this one is filled
        for i, (mark, *_) in enumerate(stops):
            cx = x0 + i * step
            on = i == k
            out.append(
                f'<circle cx="{cx:.1f}" cy="16" r="{6 if on else 4}" '
                f'fill="{accent if on else "#fff"}" stroke="{accent if i <= k else FAINT}" '
                f'stroke-width="1.5"/>'
            )
            if i:
                out.append(
                    f'<path d="M {cx - step + 6:.1f} 16 H {cx - 8:.1f}" '
                    f'stroke="{accent if i <= k else FAINT}" stroke-width="1.5"/>'
                )
            out.append(
                _mono(cx, 38, mark, 11.5, INK if on else MUTED, "middle", 600 if on else 500)
            )
        for i, line in enumerate(lines):
            y = top + i * line_h + 12
            fresh = line.strip() and line not in before
            if fresh:
                out.append(f'<circle cx="20" cy="{y - 4}" r="3" fill="{accent}"/>')
            out.append(_mono(32, y, line, size, INK if fresh else MUTED))
        x = 468
        out.append(f'<path d="M {x - 16} {top - 6} V {height - 8}" stroke="{FAINT}"/>')
        out.append(_text(x, top + 8, where, 12.5, MUTED))
        out.append(_text(x, top + 30, title, 15, INK, weight=600))
        out.append(_text(x, top + 62, "новое:", 12.5, MUTED))
        for i, note in enumerate(new):
            out.append(_text(x, top + 82 + i * 19, note, 13.5, accent))
        out.append("</svg>")
        before = set(lines)
        caption = f"{where[0].upper()}{where[1:]}, «{title}»: {' '.join(new)}."
        if k == 0:
            caption += " Точками отмечены новые строки."
        if k == len(stops) - 1 and data.get("task_end"):
            caption += " " + data["task_end"]
        frames.append(("".join(out), caption))
    return frames


def final_task_stepper(lesson: str, tone: str | None = None) -> str:
    return _stepper(final_task_frames(lesson, tone))


def final_cycle_svg(lesson: str, tone: str | None = None) -> str:
    """The steps of solving the topic task, each with its subtopics; a failed
    check returns to an earlier step."""
    data = FINALS[lesson]
    steps = data["cycle"]
    accent = accent_of(tone)
    n = len(steps)
    gap, x0, y, h = 16, 11, 16, 104
    w = (W - 2 * x0 - (n - 1) * gap) / n
    back = data.get("back")
    height = y + h + (64 if back else 18)
    names = ", ".join(title for title, _, _ in steps)
    out = [_svg(height, f"Порядок решения: {names}")]
    for k, (title, lines, refs) in enumerate(steps):
        x = x0 + k * (w + gap)
        key = k == data.get("key")
        out.append(_box(x, y, w, h, accent if key else INK, sw=2 if key else 1.5))
        out.append(_text(x + w / 2, y + 28, title, 13.5, accent if key else INK, "middle", 600))
        for i, line in enumerate(lines):
            # 12.5 px Onest is about 6.9 px a letter: keep clear of the frame
            assert len(line) * 6.9 <= w - 10, f"{lesson}: step line too long: {line}"
            out.append(_text(x + w / 2, y + 52 + i * 18, line, 12.5, MUTED, "middle"))
        out.append(_mono(x + w / 2, y + h - 10, refs, 11, MUTED, "middle"))
        if k:
            out.append(_arrow(x - gap + 2, y + h / 2, x - 2, y + h / 2, MUTED))
    if back:
        start, end, note = back
        right = x0 + start * (w + gap) + w / 2
        left = x0 + end * (w + gap) + w / 2
        bottom = y + h + 30
        out.append(
            f'<path d="M {right:.1f} {y + h + 2:.1f} V {bottom} H {left:.1f} V {y + h + 14:.1f}" '
            f'fill="none" stroke="{MUTED}" stroke-width="1.5"/>'
        )
        out.append(_arrow(left, y + h + 16, left, y + h + 2, MUTED))
        out.append(_text((left + right) / 2, bottom + 24, note, 13, MUTED, "middle"))
    out.append("</svg>")
    return "".join(out)


def final_figure_frames(lesson: str) -> list[tuple[str, str]]:
    """The topic task drawn by the topic's own builders, one figure a frame;
    every frame gets the height of the tallest, the picture at the top."""
    import figures  # registered at the end of figures.py: import on call

    drawn = [
        (figures.FIGURES[name](*args, **kwargs), caption)
        for name, args, kwargs, caption in FINALS[lesson]["frames"]
    ]
    box = re.compile(r'viewBox="0 0 (\d+(?:\.\d+)?) (\d+(?:\.\d+)?)"')
    sizes = []
    for svg, _ in drawn:
        found = box.search(svg)
        assert found, f"{lesson}: a frame without viewBox"
        sizes.append((float(found.group(1)), float(found.group(2))))
    widths = {width for width, _ in sizes}
    assert len(widths) == 1, f"{lesson}: frames of different width {widths}"
    tallest = max(height for _, height in sizes)
    frames = []
    for svg, caption in drawn:
        svg = box.sub(lambda m: f'viewBox="0 0 {m.group(1)} {tallest:g}"', svg, count=1)
        svg = re.sub(
            r' role="img" aria-label="[^"]*"', ' role="img" aria-hidden="true"', svg, count=1
        )
        frames.append((svg, caption))
    return frames


def final_figure_stepper(lesson: str) -> str:
    return _stepper(final_figure_frames(lesson))


